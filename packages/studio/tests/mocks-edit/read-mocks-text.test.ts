import {
  chmodSync,
  lstatSync,
  mkdtempSync,
  realpathSync,
  renameSync,
  rmSync,
  symlinkSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { afterEach, beforeEach, describe, expect, it } from "vitest";

import { MocksEditRefusal } from "../../src/server/mocks-edit/mocks-edit-refusal";
import { readMocksText } from "../../src/server/mocks-edit/read-mocks-text";
import { makeFedFifo, stopFifoWriters } from "../helpers/make-fed-fifo";

const NAME = "courier.mocks.ts";
const NOTHING_THROWN = Symbol("nothing thrown");

let dir: string;
let path: string;

function thrownBy(operation: () => unknown): unknown {
  try {
    operation();
  } catch (error) {
    return error;
  }
  return NOTHING_THROWN;
}

beforeEach(() => {
  dir = realpathSync(mkdtempSync(join(tmpdir(), "courier-read-mocks-")));
  path = join(dir, NAME);
});

afterEach(() => {
  stopFifoWriters();
  rmSync(dir, { recursive: true, force: true });
});

describe("readMocksText", () => {
  it("returns the bytes, the text with its byte-order mark, and the mode", () => {
    const bytes = Buffer.from([0xef, 0xbb, 0xbf, ...Buffer.from("export default {}; // é\n")]);
    writeFileSync(path, bytes);
    chmodSync(path, 0o640);

    const read = readMocksText(path, lstatSync(path), NAME);

    expect(read).toEqual({ bytes, text: "\uFEFFexport default {}; // é\n", mode: 0o640 });
  });

  it("refuses bytes that are not UTF-8", () => {
    writeFileSync(path, Buffer.from([0x65, 0x78, 0xff, 0x0a]));

    const error = thrownBy(() => readMocksText(path, lstatSync(path), NAME));

    expect(error).toBeInstanceOf(MocksEditRefusal);
    expect(error).toMatchObject({
      code: "NOT_UTF8",
      message:
        "courier.mocks.ts is not valid UTF-8 text. Studio edits only text it can read in full, so it leaves this file as it is.",
    });
  });

  it("refuses a file marked @generated in its fifth line", () => {
    writeFileSync(
      path,
      "// one\n// two\n// three\n// four\n/* @generated by a tool */\nexport default {};\n",
    );

    const error = thrownBy(() => readMocksText(path, lstatSync(path), NAME));

    expect(error).toMatchObject({
      code: "MOCKS_GENERATED",
      message:
        "Line 5 of courier.mocks.ts marks the file as generated, so an edit would be lost when it is generated again. Change what generates it instead.",
    });
  });

  it("refuses a file with a DO NOT EDIT header, whatever its line endings", () => {
    writeFileSync(path, "// DO NOT EDIT: written by a script\r\nexport default {};\r\n");

    const error = thrownBy(() => readMocksText(path, lstatSync(path), NAME));

    expect(error).toMatchObject({
      code: "MOCKS_GENERATED",
      message:
        "Line 1 of courier.mocks.ts marks the file as generated, so an edit would be lost when it is generated again. Change what generates it instead.",
    });
  });

  it("reads a file that mentions @generated only past its fifth line", () => {
    const text = "// 1\n// 2\n// 3\n// 4\n// 5\n// @generated ids are stable\nexport default {};\n";
    writeFileSync(path, text);

    expect(readMocksText(path, lstatSync(path), NAME).text).toBe(text);
  });

  it("refuses when another file took the name after the checks", () => {
    writeFileSync(path, "export default {};\n");
    const approved = lstatSync(path);
    renameSync(path, join(dir, "moved.ts"));
    writeFileSync(path, "export default { swapped: true };\n");

    const error = thrownBy(() => readMocksText(path, approved, NAME));

    expect(error).toMatchObject({
      code: "MOCKS_CHANGED_SINCE_LOAD",
      message:
        "courier.mocks.ts changed while Studio was reading it. Studio plans the edit once it has reloaded the file.",
    });
  });

  it("refuses when the name became a symbolic link after the checks", () => {
    writeFileSync(path, "export default {};\n");
    const approved = lstatSync(path);
    writeFileSync(join(dir, "elsewhere.ts"), "export default {};\n");
    unlinkSync(path);
    symlinkSync(join(dir, "elsewhere.ts"), path);

    const error = thrownBy(() => readMocksText(path, approved, NAME));

    expect(error).toMatchObject({
      code: "MOCKS_CHANGED_SINCE_LOAD",
      cause: { code: "NOT_REGULAR_FILE", cause: { code: "ELOOP" } },
    });
  });

  it("refuses when the file was removed after the checks", () => {
    writeFileSync(path, "export default {};\n");
    const approved = lstatSync(path);
    unlinkSync(path);

    const error = thrownBy(() => readMocksText(path, approved, NAME));

    expect(error).toMatchObject({
      code: "MOCKS_CHANGED_SINCE_LOAD",
      message:
        "courier.mocks.ts changed while Studio was reading it. Studio plans the edit once it has reloaded the file.",
    });
  });

  it.skipIf(process.platform === "win32")(
    "refuses a FIFO swapped in after the checks without waiting on it",
    () => {
      writeFileSync(path, "export default {};\n");
      const approved = lstatSync(path);
      unlinkSync(path);
      makeFedFifo(path, "export default {};\n");

      const error = thrownBy(() => readMocksText(path, approved, NAME));

      expect(error).toMatchObject({
        code: "MOCKS_CHANGED_SINCE_LOAD",
        cause: { code: "NOT_REGULAR_FILE", message: `${path} is a FIFO, not a regular file.` },
      });
    },
  );
});
