import { CATEGORY_CONFIG, CATEGORY_ORDER } from "./constants";
import type { AuditItem, AuditResult } from "./types";

/** Generate a markdown audit report for clipboard/PR. */
export function exportAsMarkdown(result: AuditResult): string {
  const lines: string[] = [];

  lines.push(`# Nexus Audit Report`);
  lines.push("");
  lines.push(`**Score: ${result.score}/100** | ${result.breakdown.error} errors, ${result.breakdown.warning} warnings, ${result.breakdown.hint} hints, ${result.breakdown.pass} passes`);
  lines.push("");

  for (const cat of CATEGORY_ORDER) {
    const items = result.items.filter((i) => i.category === cat);
    if (items.length === 0) continue;

    lines.push(`## ${CATEGORY_CONFIG[cat].label}`);
    lines.push("");

    for (const item of items) {
      const icon = severityIcon(item);
      lines.push(`### ${icon} ${item.title}`);
      lines.push("");
      lines.push(item.description);

      if (item.suggestion) {
        lines.push("");
        lines.push(`> **Suggestion:** ${item.suggestion}`);
      }

      if (item.codeSuggestion) {
        lines.push("");
        lines.push("```ts");
        lines.push(item.codeSuggestion);
        lines.push("```");
      }

      if (item.endpoints && item.endpoints.length > 0) {
        lines.push("");
        lines.push("| Endpoint | Detail |");
        lines.push("|----------|--------|");
        for (const ep of item.endpoints) {
          lines.push(`| \`${escapeMd(ep.label)}\` | ${escapeMd(ep.detail ?? "—")} |`);
        }
      }

      lines.push("");
    }
  }

  lines.push("---");
  lines.push(`*Generated by Nexus Studio at ${new Date(result.timestamp).toLocaleString()}*`);

  return lines.join("\n");
}

function severityIcon(item: AuditItem): string {
  const map = { error: "🔴", warning: "🟡", hint: "🔵", pass: "🟢" };
  return map[item.severity];
}

function escapeMd(str: string): string {
  return str.replace(/\|/g, "\\|").replace(/`/g, "\\`");
}
